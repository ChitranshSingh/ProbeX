"""
ProbeX AI – prompt templates for Gemini calls.

Keeping prompts in a dedicated module means:
  - They can be version-controlled and A/B tested independently.
  - Unit tests can assert on prompt content without making API calls.
  - Future team members have one place to edit and improve prompts.
"""

from __future__ import annotations


def build_remediation_prompt(
    finding_title: str,
    finding_evidence: str,
    static_remediation: str,
) -> str:
    """
    Build a Gemini prompt that asks for context-aware remediation advice.

    The prompt follows a chain-of-thought structure:
    1.  Describe the vulnerability type and observed evidence.
    2.  Provide the existing static guidance as a baseline.
    3.  Ask Gemini to produce a concise, developer-friendly improvement.

    Parameters
    ----------
    finding_title:
        e.g. 'Reflected Cross-Site Scripting'.
    finding_evidence:
        Raw evidence snippet from the HTTP response (<500 chars recommended).
    static_remediation:
        The template-driven guidance already generated by the engine.

    Returns
    -------
    str
        A formatted prompt string ready to send to the Gemini API.
    """
    return f"""You are a senior application security engineer writing remediation guidance
for a development team. Be concise, practical, and code-focused.

## Vulnerability
{finding_title}

## Evidence
```
{finding_evidence[:500]}
```

## Existing guidance (baseline)
{static_remediation}

## Your task
Improve the existing guidance above. Provide:
1. A one-sentence root-cause explanation.
2. A concrete code-level fix with a short before/after snippet (pseudocode is fine).
3. Any additional OWASP or CWE references the developer should review.

Keep the total response under 300 words. Do not repeat the vulnerability name as a heading."""
